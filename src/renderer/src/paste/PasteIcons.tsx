export function PasteTypeIcon({ type }: { type: PasteItemType }): JSX.Element {
  if (type === 'image') return <ImageIcon />
  if (type === 'link') return <LinkIcon />
  if (type === 'file') return <FileIcon />
  if (type === 'rich') return <RichTextIcon />
  return <TextIcon />
}

